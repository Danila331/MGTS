const concerns = ["clarity", "support", "workload"];
const improvements = ["improvement", "supportImprovement", "workloadImprovement"];

export function scenarioForDemoRound(rounds, person, period) {
  const scores = rounds[period];
  const low = concerns.filter((_, index) => scores[index] <= 2);
  if (low.length) return low[(person + period) % low.length];

  const previous = rounds[period - 1];
  const improved = previous && previous.findIndex((value, index) => index < concerns.length && value <= 2 && scores[index] > value);
  if (typeof improved === "number" && improved >= 0) return improvements[improved];

  if ((person + period) % 4 === 0) return "growth";
  if (person % 5 === 0) return "teamwork";
  return "neutral";
}
